#!/usr/bin/env python3
"""Generate runtime/src/import_stubs.cpp: a weak fallback for every kernel/XAM import used by
the recompiled executables. Real implementations elsewhere in runtime/ override them.

usage: gen_import_stubs.py   (run from the repo root after tools/prepare.sh)
"""
import re

names = set()
for m in ("mp", "zm"):
    for line in open(f"ppc/{m}/ppc_recomp_shared.h"):
        g = re.match(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);", line)
        if g:
            names.add(g.group(1))

out = ["// Generated by tools/gen_import_stubs.py - do not edit.",
       "// Weak fallbacks: log the first call of each unimplemented import, return 0.",
       '#include "guest.h"', '#include "stubs.h"', ""]
for n in sorted(names):
    out.append(f'GUEST_IMPORT_WEAK({n}) {{ ImportUnimplemented(ctx, "{n}"); }}')
open("runtime/src/import_stubs.cpp", "w").write("\n".join(out) + "\n")
print(f"{len(names)} import stubs")
