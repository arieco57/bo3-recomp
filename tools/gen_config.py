#!/usr/bin/env python3
"""Generate the XenonRecomp TOML config for one BO3 executable.

usage: gen_config.py <mp|zm> <setjmp_hex> <longjmp_hex>

Inputs (produced by tools/prepare.sh):
  private/<m>/info.txt, image.bin, recomp_addresses.toml   (bo3prep)
  config/BO3_<M>_functions.toml                            (bo3switch)
Output:
  config/BO3_<M>.toml
"""
import collections
import struct
import sys

m, setjmp, longjmp = sys.argv[1], sys.argv[2], sys.argv[3]
M = m.upper()
d = f"private/{m}"
BASE = 0x82000000

secs = {}
for line in open(f"{d}/info.txt", encoding="latin-1"):
    p = line.split()
    if len(p) == 5 and p[2] == "size":
        secs[p[0]] = (int(p[1], 16), int(p[3], 16), p[4])
img = open(f"{d}/image.bin", "rb").read()

# Exception handler records (handler ptr + data ptr) sit in the 8 bytes before every .pdata
# function with the ExceptionFlag bit; they must be skipped as data, not decoded as code.
code = [(b, s) for b, s, k in secs.values() if k == "CODE"]
pb, ps, _ = secs[".pdata"]
handlers = collections.Counter()
for o in range(pb - BASE, pb - BASE + ps, 8):
    begin, fl = struct.unpack_from(">II", img, o)
    if begin and (fl >> 31) & 1:
        h = struct.unpack_from(">I", img, begin - 8 - BASE)[0]
        if any(b <= h < b + s for b, s in code):
            handlers[h] += 1

addresses = "".join(l for l in open(f"{d}/recomp_addresses.toml") if not l.startswith("#"))
functions = "".join(l for l in open(f"config/BO3_{M}_functions.toml") if not l.startswith("#"))
title = "Multiplayer / Freerun (default.xex)" if m == "mp" else "Zombies (default_zm.xex)"
inv = "".join(f"    {{ data = 0x{h:08X}, size = 8 }}, # exception handler record ({n} functions)\n"
              for h, n in handlers.most_common())

open(f"config/BO3_{M}.toml", "w").write(f"""# XenonRecomp config: Call of Duty: Black Ops III (Xbox 360, title 4156091D) - {title}
# Base disc XEX + Title Update 1 delta patch. Generated by tools/gen_config.py - do not hand-edit,
# rerun tools/prepare.sh instead (or add overrides to tools/gen_config.py).

[main]
file_path = "../private/{m}/default.xex"
patch_file_path = "../private/{m}/default.xexp"
patched_file_path = "../private/{m}/default_patched.xex"
out_directory_path = "../ppc/{m}"
switch_table_file_path = "BO3_{M}_switch_tables.toml"

# Optimizations: keep OFF until the recompilation runs correctly (README recommendation).
skip_lr = false
skip_msr = false
ctr_as_local = false
xer_as_local = false
reserved_as_local = false
cr_as_local = false
non_argument_as_local = false
non_volatile_as_local = false

# Register save/restore helpers (byte-pattern match, tools/bo3prep)
{addresses}
# Found via RtlUnwind caller (longjmp) and the jmp_buf store sequence (setjmp); verified by disassembly
setjmp_address = {setjmp}
longjmp_address = {longjmp}

# Leaf functions with jump tables (tools/bo3prep/bo3switch)
{functions}
invalid_instructions = [
    {{ data = 0x00000000, size = 4 }}, # padding
{inv}]
""")
print(f"config/BO3_{M}.toml: {len(handlers)} exception handler records")
